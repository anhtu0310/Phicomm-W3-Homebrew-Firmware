static void scs(bool high)
{
    if (high) {
        hal_gpio_set_output(JDI_PIN_SCS, HAL_GPIO_DATA_HIGH);
        hal_gpt_delay_us(6);                    /* tsSCS */
    } else {
        hal_gpt_delay_us(2);                    /* thSCS */
        hal_gpio_set_output(JDI_PIN_SCS, HAL_GPIO_DATA_LOW);
    }
}

static void spi_send(const uint8_t *buf, uint32_t len)
{
    while (len) {
        uint32_t n = len > HAL_SPI_MAXIMUM_POLLING_TRANSACTION_SIZE ?
                     HAL_SPI_MAXIMUM_POLLING_TRANSACTION_SIZE : len;
        hal_spi_master_send_polling(JDI_SPI_PORT, (uint8_t *)buf, n);
        buf += n;
        len -= n;
    }
}

static void extcomin_start(uint32_t hz)
{
    uint32_t total = 0;

    hal_pwm_set_frequency(JDI_PWM_EXTCOMIN, hz, &total);
    hal_pwm_set_duty_cycle(JDI_PWM_EXTCOMIN, total * 10 / 100);
    hal_pwm_start(JDI_PWM_EXTCOMIN);
}

void jdi_lcd_init(void)
{
    hal_spi_master_config_t spi = {
        .clock_frequency = JDI_SPI_FREQ_HZ,
        .slave_port = HAL_SPI_MASTER_SLAVE_0,
        .bit_order = HAL_SPI_MASTER_MSB_FIRST,
        .polarity = HAL_SPI_MASTER_CLOCK_POLARITY0,
        .phase = HAL_SPI_MASTER_CLOCK_PHASE0,
    };

    /* The panel is supplied by the PMIC VMC LDO at 2.8 V (stock bsp_lcd_init
     * does exactly this). It keeps its state across an MCU reset but is off
     * after a power cycle; without it the image builds up slowly and fades. */
    PMIC_VR_VOSEL_INIT_CONFIG(PMIC_VMC, PMIC_LDO_2P8V);
    PMIC_VR_CONTROL(PMIC_VMC, PMIC_VR_CTL_ENABLE);
    hal_gpt_delay_ms(5);

    /* Pin modes come from the EPT config; make the control pins explicit. */
    hal_gpio_init(JDI_PIN_SCS);
    hal_pinmux_set_function(JDI_PIN_SCS, 0);
    hal_gpio_set_direction(JDI_PIN_SCS, HAL_GPIO_DIRECTION_OUTPUT);
    hal_gpio_set_output(JDI_PIN_SCS, HAL_GPIO_DATA_LOW);

    hal_gpio_init(JDI_PIN_DISP);
    hal_pinmux_set_function(JDI_PIN_DISP, 0);
    hal_gpio_set_direction(JDI_PIN_DISP, HAL_GPIO_DIRECTION_OUTPUT);

    hal_spi_master_init(JDI_SPI_PORT, &spi);

    hal_pinmux_set_function(HAL_GPIO_11, HAL_GPIO_11_PWM0);
    hal_pwm_init(JDI_PWM_EXTCOMIN, HAL_PWM_CLOCK_32KHZ);
    hal_pwm_set_advanced_config(JDI_PWM_EXTCOMIN, HAL_PWM_CLOCK_DIVISION_8);

    jdi_lcd_all_clear();
    jdi_lcd_display_on(true);
    extcomin_start(JDI_EXTCOMIN_HZ);

    memset(s_fb, (JDI_WHITE << 4) | JDI_WHITE, sizeof(s_fb));
    memset(s_shown, (JDI_WHITE << 4) | JDI_WHITE, sizeof(s_shown));
}

void jdi_lcd_display_on(bool on)
{
    hal_gpio_set_output(JDI_PIN_DISP, on ? HAL_GPIO_DATA_HIGH : HAL_GPIO_DATA_LOW);
    hal_gpt_delay_us(30);
}

void jdi_lcd_all_clear(void)
{
    static const uint8_t cmd[2] = {CMD_ALL_CLEAR, 0x00};

    scs(true);
    spi_send(cmd, sizeof(cmd));
    scs(false);
}

void jdi_lcd_fill(uint8_t color)
{
    memset(s_fb, ((color & 0xF) << 4) | (color & 0xF), sizeof(s_fb));
}

void jdi_lcd_set_pixel(int x, int y, uint8_t color)
{
    uint8_t *p;

    if (x < 0 || y < 0 || x >= JDI_WIDTH || y >= JDI_HEIGHT) {
        return;
    }
    p = &s_fb[y][x >> 1];
    if (x & 1) {
        *p = (*p & 0xF0) | (color & 0x0F);
    } else {
        *p = (*p & 0x0F) | ((color & 0x0F) << 4);
    }
}

void jdi_lcd_fill_rect(int x, int y, int w, int h, uint8_t color)
{
    int i, j;

    for (j = y; j < y + h; j++) {
        for (i = x; i < x + w; i++) {
            jdi_lcd_set_pixel(i, j, color);
        }
    }
}

int jdi_lcd_draw_text(int x, int y, const char *s, uint8_t fg, uint8_t bg, int scale)
{
    for (; *s; s++) {
        char c = (*s < 32 || *s > 126) ? '?' : *s;
        const uint8_t *g = font5x7[c - 32];
        int col, row;

        for (col = 0; col < 6; col++) {
            uint8_t bits = col < 5 ? g[col] : 0;
            for (row = 0; row < 8; row++) {
                uint8_t color = (bits >> row) & 1 ? fg : bg;
                jdi_lcd_fill_rect(x + col * scale, y + row * scale, scale, scale, color);
            }
        }
        x += 6 * scale;
    }
    return x;
}

/* Builds one panel line (cmd, address, 36 data bytes) from framebuffer row y. */
static void build_line(uint8_t *dst, int y)
{
    const uint8_t *src = s_fb[y];
    int i;

    dst[0] = CMD_UPDATE_4BIT;
#if JDI_ROTATE_180
    dst[1] = (uint8_t)(JDI_HEIGHT - y);
    for (i = 0; i < LINE_BYTES; i++) {
        uint8_t b = src[LINE_BYTES - 1 - i];
        dst[2 + i] = (uint8_t)((b << 4) | (b >> 4));
    }
#else
    dst[1] = (uint8_t)(y + 1);
    memcpy(&dst[2], src, LINE_BYTES);
#endif
}

void jdi_lcd_flush(bool force)
{
    uint32_t len = 0;
    int y;

    for (y = 0; y < JDI_HEIGHT; y++) {
        if (!force && memcmp(s_fb[y], s_shown[y], LINE_BYTES) == 0) {
            continue;
        }
        build_line(&s_tx[len], y);
        memcpy(s_shown[y], s_fb[y], LINE_BYTES);
        len += LINE_FRAME_BYTES;
    }
    if (len == 0) {
        return;
    }
    s_tx[len++] = 0x00;
    s_tx[len++] = 0x00;

    scs(true);
    spi_send(s_tx, len);
    scs(false);
}
